"""Build transition-data.js: the catalogue layers that carry one scale into the next.

  - HYG v4.1 (github.com/astronexus/HYG-Database, hyg/CURRENT/hygdata_v41.csv, CC BY-SA 4.0): every star
    brighter than visual magnitude 6.5 (about what an eye sees on a dark night) within 1,000 light-years,
    the Sun left out. Distances are HYG's (mostly Hipparcos/Gaia parallaxes); beyond a few hundred
    light-years they are uncertain by tens of percent.
    Packed per star: RA uint16, Dec int16, distance (1/60 ly) uint16, colour index B-V (×50) int8,
    magnitude ((m + 2) × 20) uint8.
  - Harris 1996 (2010 edition), Catalog of Parameters for Milky Way Globular Clusters, Part I
    (physics.mcmaster.ca/~harris/mwgc.dat; free of charge, redistributed with reference to the source):
    every cluster's galactic longitude, latitude and distance from the Sun.
    Packed per cluster: l uint16, b int16, distance (0.1 kpc) uint16.
  - The "Council of Giants" around the Local Group in the Local Sheet (McCall 2014, MNRAS 440, 405; distances
    as tabulated by Wikipedia's "Local Sheet" article, read 10 Nov 2026), positions from OpenNGC
    (github.com/mattiaverga/OpenNGC NGC.csv, CC BY-SA 4.0). The three members not in NGC/IC (Maffei 1 and 2,
    the Circinus Galaxy) are left out rather than given positions from elsewhere.
Usage: python3 tools/build_transition.py hygdata_v41.csv mwgc.dat NGC.csv > transition-data.js
"""
import base64, csv, hashlib, struct, sys
PC_LY = 3.26156
hyg_path, harris_path, ngc_path = sys.argv[1], sys.argv[2], sys.argv[3]
sha = lambda p: hashlib.sha256(open(p, 'rb').read()).hexdigest()
stars, n = bytearray(), 0
for r in csv.DictReader(open(hyg_path, encoding='utf-8')):
    if r['proper'] == 'Sol': continue
    try: d, m = float(r['dist']), float(r['mag'])
    except ValueError: continue
    if not (0 < d < 100000): continue          # 100000 pc is HYG's "no parallax" placeholder
    ly = d * PC_LY
    if ly > 1000 or m > 6.5: continue
    ci = float(r['ci']) if r['ci'] else 0.65
    ra, dec = float(r['ra']) * 15, float(r['dec'])
    stars += struct.pack('<HhHbB', round(ra / 360 * 65535) % 65536, round(dec / 90 * 32767), round(ly * 60),
                         max(-128, min(127, round(ci * 50))), max(0, min(255, round((m + 2) * 20)))); n += 1
gcs, ng, part = bytearray(), 0, False
for line in open(harris_path, encoding='latin-1'):
    if 'Part I:' in line: part = True; continue
    if 'Part II' in line: break
    if not part: continue
    f = line.split()                              # ... L B R_Sun R_gc X Y Z: the last seven columns
    try: l, b, rs = float(f[-7]), float(f[-6]), float(f[-5]); [float(v) for v in f[-4:]]
    except (ValueError, IndexError): continue
    if not (0 <= l <= 360 and -90 <= b <= 90 and rs > 0): continue
    gcs += struct.pack('<HhH', round(l / 360 * 65535) % 65536, round(b / 90 * 32767), round(rs * 10)); ng += 1
GIANTS = [('NGC0253', 'Sculptor Galaxy', 11), ('IC0342', 'IC 342', 11), ('NGC3031', 'M81', 12), ('NGC3034', 'M82', 11),
          ('NGC4736', 'M94', 15), ('NGC4826', 'M64', 16), ('NGC5236', 'M83', 16), ('NGC5128', 'Centaurus A', 11), ('NGC4945', 'NGC 4945', 12)]
def deg(v, hours):
    sg = -1 if v.startswith('-') else 1; p = [float(x) for x in v.lstrip('+-').split(':')]
    return round(sg * (p[0] + p[1] / 60 + p[2] / 3600) * (15 if hours else 1), 4)
ngc = {r['Name']: r for r in csv.DictReader(open(ngc_path, encoding='utf-8'), delimiter=';')}
giants = [{'id': k, 'name': nm, 'mly': d, 'ra': deg(ngc[k]['RA'], True), 'dec': deg(ngc[k]['Dec'], False)} for k, nm, d in GIANTS]
import json
print(f'''// GENERATED by tools/build_transition.py. Sources (see docs/sources.md):
//  HYG v4.1 (astronexus/HYG-Database, CC BY-SA 4.0), sha256 {sha(hyg_path)[:16]}: {n} stars, V <= 6.5, <= 1,000 ly.
//    Packed: RA uint16, Dec int16, distance (1/60 ly) uint16, B-V x50 int8, (V + 2) x20 uint8.
//  Harris 1996 (2010 edition) Milky Way globular clusters, Part I, sha256 {sha(harris_path)[:16]}: {ng} clusters.
//    Packed: l uint16, b int16, distance from the Sun (0.1 kpc) uint16.
export const HYG_COUNT = {n};
export const HYG_PACKED = '{base64.b64encode(bytes(stars)).decode()}';
export const GC_COUNT = {ng};
export const GC_PACKED = '{base64.b64encode(bytes(gcs)).decode()}';
//  Council of Giants (McCall 2014; distances in Mly as tabulated on Wikipedia), RA/Dec from OpenNGC, sha256 {sha(ngc_path)[:16]}.
export const GIANTS = {json.dumps(giants, ensure_ascii=False)};''')
