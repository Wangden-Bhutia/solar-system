"""Build laniakea-data.js from OpenNGC (https://github.com/mattiaverga/OpenNGC, CC BY-SA 4.0).

Every NGC/IC galaxy with a measured redshift becomes one point: position from RA/Dec, distance from the
Hubble law d = cz / H0 (H0 = 70 km/s/Mpc). Galaxies closer than cz = 1000 km/s are left out: there,
their own motions swamp the expansion and the Hubble law gives nonsense (the Local Group level shows them).
Packed as base64: per galaxy RA (uint16), Dec (int16), distance in 0.1 Mly (uint16), kind (uint8).
Usage: python3 tools/build_laniakea.py path/to/OpenNGC/database_files/NGC.csv > laniakea-data.js
"""
import base64, csv, struct, sys
C, H0, MLY_PER_MPC = 299792.458, 70.0, 3.26156
def deg(s, hours):
    sg = -1 if s.startswith('-') else 1; p = [float(x) for x in s.lstrip('+-').split(':')]
    v = p[0] + p[1] / 60 + p[2] / 3600; return sg * v * (15 if hours else 1)
out, n, kinds = bytearray(), 0, [0, 0, 0]
for r in csv.DictReader(open(sys.argv[1], encoding='utf-8'), delimiter=';'):
    if r['Type'] not in ('G', 'GPair', 'GTrpl', 'GGroup') or not r['Redshift'] or not r['RA']: continue
    cz = float(r['Redshift']) * C
    if cz < 1000: continue
    d = cz / H0 * MLY_PER_MPC
    if d > 6500: continue
    h = (r['Hubble'] or '').strip(); k = 0 if h.startswith(('E', 'S0', 'cD')) else 1 if h.startswith('S') else 2
    ra, dec = deg(r['RA'], True), deg(r['Dec'], False)
    out += struct.pack('<HhHB', round(ra / 360 * 65535) % 65536, round(dec / 90 * 32767), round(d * 10), k); n += 1; kinds[k] += 1
b64 = base64.b64encode(bytes(out)).decode()
print(f'''// GENERATED by tools/build_laniakea.py from OpenNGC (github.com/mattiaverga/OpenNGC), CC BY-SA 4.0.
// {n} NGC/IC galaxies with measured redshifts (ellipticals/S0 {kinds[0]}, spirals {kinds[1]}, other {kinds[2]}).
// Distance = Hubble law, cz / 70 km/s/Mpc. Packed: RA uint16, Dec int16, distance (0.1 Mly) uint16, kind uint8.
export const NGC_COUNT = {n};
export const NGC_PACKED = '{b64}';''')
