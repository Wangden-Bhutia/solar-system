#!/usr/bin/env python3
"""Regenerate the voice clips (world cards, labs, Earth–Moon adventure) from voice/lines.json so audio never drifts from on-screen text.
Voice: Kokoro-82M v1.0 (Apache-2.0 weights) via kokoro-onnx (MIT), speaker bm_george, speed 0.85.
Needs: pip install kokoro-onnx soundfile; ffmpeg; model files (env KOKORO_MODEL, KOKORO_VOICES).
Writes voice/<id>.mp3 (mono 24 kHz, 32 kbps), voice/lines.js and voice/manifest.json (text hash per clip; unchanged clips are skipped)."""
import json, os, hashlib, subprocess, tempfile, sys
import soundfile as sf
from kokoro_onnx import Kokoro
VOICE, SPEED = 'bm_george', 0.85
root = os.path.join(os.path.dirname(__file__), '..', 'voice')
lines = json.load(open(os.path.join(root, 'lines.json')))
man_p = os.path.join(root, 'manifest.json')
man = json.load(open(man_p)) if os.path.exists(man_p) else {}
k = Kokoro(os.environ.get('KOKORO_MODEL', 'kokoro-v1.0.onnx'), os.environ.get('KOKORO_VOICES', 'voices-v1.0.bin'))
for cid, text in lines.items():
    h = hashlib.sha1(f'{VOICE}|{SPEED}|{text}'.encode()).hexdigest()[:12]
    out = os.path.join(root, f'{cid}.mp3')
    if man.get(cid, {}).get('hash') == h and os.path.exists(out): continue
    audio, sr = k.create(text, voice=VOICE, speed=SPEED, lang='en-gb')
    with tempfile.NamedTemporaryFile(suffix='.wav') as w:
        sf.write(w.name, audio, sr)
        # gentle warmth: slight low-shelf, trim edges, fade-out
        subprocess.run(['ffmpeg', '-loglevel', 'error', '-y', '-i', w.name, '-af', 'bass=g=2:f=180,afade=t=out:st=%0.2f:d=0.08' % max(0, len(audio)/sr - 0.08),
                        '-ac', '1', '-ar', '24000', '-b:a', '32k', out], check=True)
    man[cid] = {'hash': h, 'dur': round(len(audio) / sr, 2), 'text': text}
    print('built', cid, man[cid]['dur'], 's')
for cid in list(man):
    if cid not in lines: man.pop(cid)
json.dump(man, open(man_p, 'w'), indent=1, ensure_ascii=False)
with open(os.path.join(root, 'lines.js'), 'w') as f:
    f.write('// Generated by tools/build-voice.py from voice/lines.json. Do not edit.\n')
    f.write('export const LINES = ' + json.dumps(lines, ensure_ascii=False, indent=1) + ';\n')
    f.write('export const VOICE = ' + json.dumps({'name': VOICE, 'speed': SPEED, 'dur': {c: m['dur'] for c, m in man.items()}, 'hash': {c: m['hash'] for c, m in man.items()}}) + ';\n')
